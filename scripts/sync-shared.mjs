/**
 * Copy shared/ into the two places that can load it. Neither an MV3 service
 * worker nor a Worker's assets directory can reach a sibling folder, so the one
 * source of truth is copied into both and the copies are committed - `Load
 * unpacked` then works from a fresh clone with no npm install.
 *
 * `--check` writes nothing and exits non-zero if any copy has drifted, which is
 * what CI runs: an edited copy is a bug that only shows up in one runtime.
 *
 * The only build step in the project. Keep it that way.
 */

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "shared");
const targets = [
  join(root, "extension", "shared"),
  join(root, "web", "public", "vendor", "shared"),
];
const check = process.argv.includes("--check");

const NOTICE = `Generated by \`npm run sync-shared\` from /shared. Do not edit these copies.\n`;

const SPLICES = [
  { file: "matching.js", marker: "MATCHING" },
  { file: "page-nav.js", marker: "PAGENAV" },
];

const files = (await readdir(source)).filter((f) => f.endsWith(".js"));
if (files.length === 0) throw new Error("shared/ has no .js files to sync");

/** Every file this script owns, mapped to the content it should have. */
const wanted = new Map();
wanted.set(join(root, "extension", "content-agent.js"), await splicedContentScript());
for (const target of targets) {
  for (const file of files)
    wanted.set(join(target, file), await readFile(join(source, file), "utf8"));
  wanted.set(join(target, "README.md"), NOTICE);
}

const drifted = [];
for (const [path, content] of wanted) {
  const current = await readFile(path, "utf8").catch(() => null);
  if (current === content) continue;
  drifted.push(relative(root, path));
  if (!check) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
}

if (check && drifted.length > 0) {
  console.error(
    `out of sync with shared/ - run \`npm run sync-shared\`:\n  ${drifted.join("\n  ")}`
  );
  process.exit(1);
}
console.log(drifted.length === 0 ? "shared copies are in sync" : `synced ${drifted.join(", ")}`);

/**
 * A content script is injected as a file, not a module graph, so it cannot
 * import - but a second copy of shared DOM logic would drift. Generating the
 * content script's copy from the shared module keeps one source of truth and a
 * file that loads with no build. Order matters: page-nav uses matching.
 */
async function splicedContentScript() {
  let script = await readFile(join(root, "extension", "content-agent.js"), "utf8");

  for (const { file, marker } of SPLICES) {
    const START = `// AALTO:${marker}-START`;
    const END = `// AALTO:${marker}-END`;
    const from = script.indexOf(START);
    const to = script.indexOf(END);
    if (from === -1 || to === -1)
      throw new Error(`content-agent.js is missing its ${marker} markers`);

    const shared = await readFile(join(source, file), "utf8");
    // Strip the header and the imports, and turn exports into plain
    // declarations - the spliced blocks share one scope instead.
    const body = shared
      .slice(shared.indexOf("*/") + 2)
      .replace(/^import .*;\n/gm, "")
      .replace(/^export /gm, "")
      .trim();
    script = `${script.slice(0, from + START.length)}\n${body}\n${script.slice(to)}`;
  }
  return script;
}
